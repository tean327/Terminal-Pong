int ReadKey(void)
{
    unsigned char c;
    ssize_t n = read(STDIN_FILENO, &c, 1);
    return (n == 1) ? c : 0;
}

char* GenerateGridStr()
{
    char *str = (char*)malloc(sizeof(char) * GRID_HEIGHT*GRID_WIDTH+GRID_HEIGHT*2+1);
    if(!str)
        return NULL;
    
    int k = 0;
    for(int i = 0; i < GRID_HEIGHT; i++, k++)
    {
        for(int j = 0; j < GRID_WIDTH; j++, k++)
        {
            str[k] = grid[i][j];
        }    
        str[k++] = '\r';
        str[k] = '\n';
    }
    str[k+1] = '\0';
    return str;
}

int ChangeGrid(Player* p1, Player* p2, Ball* b)
{

    if(b->posX <= 0)
    {
        p2->score++;
        return 1;
    }
    if(b->posX >= GRID_WIDTH)
    {
        p1->score++;
        return 1;
    }

    grid[0][1] = grid[GRID_HEIGHT-1][1] = '#';
    grid[0][GRID_WIDTH-1] = grid[GRID_HEIGHT][GRID_WIDTH-1] = '#';

    BallProcess(b, p1, p2);
    grid[(int)b->posY][(int)b->posX] = '@';

    int key = ReadKey();
    if(key == 'z' && p1->posY-1 > 1)
        p1->posY--;
    
    if(key == 's' && p1->posY+1 < GRID_HEIGHT-2)
        p1->posY++;
    
    if(key == 'p' && p2->posY-1 > 1)
        p2->posY--;
    
    if(key == 'm' && p2->posY+1 < GRID_HEIGHT-2)
        p2->posY++;


    for(int i = 1; i < GRID_HEIGHT-1; i++)
    {
        for(int j = 1; j < GRID_WIDTH-1; j++)
        {
            if(j == 1)
            {
                if(i == p1->posY-1 || i == p1->posY+1 || i == p1->posY)
                    grid[i][j] = '|';
                else
                    grid[i][j] = ' ';
            }
            else if(j == GRID_WIDTH-2)
            {
                if(i == p2->posY-1 || i == p2->posY+1 || i == p2->posY)
                    grid[i][j] = '|';
                else
                    grid[i][j] = ' ';
            }
            else if(i == (int)(b->posY+0.5f) && j == (int)(b->posX+0.5f))
                grid[i][j] = '@';
            else
                grid[i][j] = ' ';
        }    
    }
    return 0;
}
